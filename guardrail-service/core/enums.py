"""
Canonical enumerations for the Guardrail Service.
All dimension and role names here are the authoritative source of truth
and must match evaluations.yaml exactly.
"""
from enum import Enum


class ContentRole(str, Enum):
    """Role of the content being submitted for evaluation."""
    USER_PROMPT    = "user_prompt"      # Input from a human or upstream agent
    LLM_RESPONSE   = "llm_response"     # Output generated by the LLM
    AGENT_TO_AGENT = "agent_to_agent"   # Inter-agent communication
    TOOL_CALL      = "tool_call"        # Pre/post tool execution (Phase 4+)


class EvaluationStatus(str, Enum):
    """Lifecycle status of an evaluation dimension."""
    ACTIVE   = "active"    # Evaluated and contributes to MRA verdict
    DEFERRED = "deferred"  # Registered but excluded from verdict synthesis


class ResultStatus(str, Enum):
    """Normalised result status returned per evaluation dimension."""
    PASS    = "PASS"     # Score in LOW band  (1-3)
    WARNING = "WARNING"  # Score in MEDIUM band (4-6)
    FLAGGED = "FLAGGED"  # Score in HIGH band   (7-9)
    UNKNOWN = "UNKNOWN"  # Provider error or unsupported dimension
