"""
Policy Engine response schemas.
Matches SRS §4.5 PolicyEvaluateResponse.
"""
from enum import Enum
from typing import Dict, List, Optional
from pydantic import BaseModel, Field, model_validator
from datetime import datetime


class Verdict(str, Enum):
    PERMISSIVE = "PERMISSIVE"  # All evaluations within permissive band — execution proceeds
    NORMATIVE  = "NORMATIVE"   # One or more in normative band, none coercive — proceeds with warning
    COERCIVE   = "COERCIVE"    # One or more in coercive band — execution blocked


# ── Directive taxonomy ─────────────────────────────────────────────────────────
#
# Directives carry *actionable instructions* from the PE (or Sentinel via PE)
# to the SDK.  They are distinct from the verdict (which describes what was
# detected) — a directive says what to DO about it.
#
# Design notes
# ─────────────
# • DirectiveAction is intentionally small.  PERMISSIVE/NORMATIVE/COERCIVE already
#   encode detection severity; we only add actions that the SDK must execute
#   differently from the standard verdict path.
# • REQUIRE_HUMAN_REVIEW is the primary new signal: it pauses agent execution
#   and routes the session to the HITL queue.
# • REDACT is already handled by enforcement-mode logic but is surfaced as a
#   directive when the PE wants to provide specific substitute text (e.g. a
#   context-aware refusal generated by the MessageWriter).
# • Each REQUIRE_HUMAN_REVIEW directive carries a HITLCategory so the HITL
#   UI can present the right reviewer options without any frontend logic changes.

class DirectiveAction(str, Enum):
    REDACT               = "redact"
    # Replace agent/LLM output with PE-provided response_text.

    REQUIRE_HUMAN_REVIEW = "require_human_review"
    # Pause execution; route session to HITL queue.
    # SDK raises HITLInterrupt with the full Directive payload.


class HITLCategory(str, Enum):
    AGENT_ARBITRATION = "agent_arbitration"
    # Deadlocked multi-agent negotiation: same agent pair has exchanged
    # proposals without reaching consensus (propose-and-dispose pattern).
    # Triggered by: Sentinel agent_circular_dispute (≥ 3 same-pair rounds).
    # Reviewer options: approve_recommendation, select_alternative, reject_all,
    #                   request_more_information, escalate_to_advisor.

    SANCTIONS_REVIEW  = "sanctions_review"
    # Transaction flagged for AML/sanctions exposure — compliance sign-off required.
    # Triggered by: PE policy pack with hitl_trigger=True on sanctions dimensions.
    # Reviewer options: approve, approve_with_waiver, temporary_exemption,
    #                   reject, update_policy, escalate_to_compliance, file_sar.


class DirectiveSource(str, Enum):
    PE          = "pe"           # deterministic policy pack evaluation
    SENTINEL    = "sentinel"     # cross-turn pattern detection
    COORDINATOR = "coordinator"  # coordinator agent arbitration


# Default reviewer options surfaced in the HITL UI per category.
# SDK/dashboard uses these when the Directive.options list is empty.
HITL_DEFAULT_OPTIONS: Dict[str, List[str]] = {
    HITLCategory.AGENT_ARBITRATION.value: [
        "approve_recommendation",   # accept the agents' final proposed option as-is
        "select_alternative",       # choose a different option from the candidate list
        "reject_all",               # none of the proposals are acceptable
        "request_more_information", # additional context needed before deciding
        "escalate_to_advisor",      # route to a human financial advisor
    ],
    HITLCategory.SANCTIONS_REVIEW.value: [
        "approve",                  # clear the flag — transaction proceeds
        "approve_with_waiver",      # approve with documented waiver on file
        "temporary_exemption",      # time-limited clearance (reviewer sets expiry)
        "reject",                   # block the transaction
        "update_policy",            # edge case — flag rule for compliance policy review
        "escalate_to_compliance",   # senior compliance officer required
        "file_sar",                 # file Suspicious Activity Report (BSA §5318)
    ],
}


class Directive(BaseModel):
    """
    A structured, actionable instruction from the PE (or Sentinel via PE) to the SDK.

    The SDK processes directives in strict priority order after receiving a
    PolicyEvaluateResponse:
        REQUIRE_HUMAN_REVIEW  →  raise HITLInterrupt (highest priority)
        REDACT                →  substitute content with response_text

    Multiple directives may be present (e.g. REDACT + REQUIRE_HUMAN_REVIEW from
    different sources); the SDK applies the highest-priority one.
    """
    action:   DirectiveAction
    category: Optional[HITLCategory] = None  # required when action=REQUIRE_HUMAN_REVIEW
    reason:   str                    = ""    # operator-facing explanation
    options:  List[str]              = Field(default_factory=list)
    # reviewer choices; auto-populated from HITL_DEFAULT_OPTIONS when empty
    source:   DirectiveSource        = DirectiveSource.PE
    metadata: Dict                   = Field(default_factory=dict)
    # extensible context — e.g. candidate card list for AGENT_ARBITRATION

    @model_validator(mode="after")
    def _fill_default_options(self) -> "Directive":
        """Auto-populate reviewer options from defaults when not explicitly set."""
        if (
            self.action == DirectiveAction.REQUIRE_HUMAN_REVIEW
            and not self.options
            and self.category is not None
            and self.category.value in HITL_DEFAULT_OPTIONS
        ):
            self.options = list(HITL_DEFAULT_OPTIONS[self.category.value])
        return self


class FailedEvaluation(BaseModel):
    """Per-dimension detail for non-permissive results."""
    dimension: str
    score:     Optional[int]
    status:    str    # WARNING | FLAGGED
    provider:  Optional[str] = None


class PolicyResult(BaseModel):
    """Per-policy verdict detail included when verdict is non-permissive."""
    policy_name: str
    score:       Optional[int]
    verdict:     Verdict
    severity:    int        # 1 (low) – 3 (high)
    remediation: Optional[str] = None


class SessionSummary(BaseModel):
    """
    Per-session composite trust snapshot attached to every evaluation response
    when a session_id is present.

    composite_score — weighted average of normalised worst-case dimension scores
                      accumulated across all turns this session.
                      Scale: 1.0 = fully trusted / clean, 0.0 = maximum risk.
    worst_verdict   — the highest-severity verdict seen in any turn this session.
    turn_count      — number of evaluation turns completed.
    dimension_scores — worst raw score (1-9) per dimension seen this session.
    escalated       — True when session accumulation produced a verdict higher
                      than the per-turn verdict on at least one prior turn
                      (audit-only; the per-turn verdict is always returned to
                      the application).
    """
    turn_count:       int
    composite_score:  float                  # 0.0 (risky) – 1.0 (safe)
    worst_verdict:    str                    # PERMISSIVE | NORMATIVE | COERCIVE
    dimension_scores: Dict[str, int]         # worst raw score per dim
    escalated:        bool


class RenderedMessage(BaseModel):
    """
    Fully-rendered, structured governance message produced by MessageWriter.

    Replaces the old flat remediations[] string list.  The SDK (GovernanceResult)
    still carries remediations: List[str] for v1 stability — the orchestrator
    bridges rendered_message into that field so SDK consumers receive the rich
    text without requiring a SDK version bump.

    template_type:
      'A' — Trust Platform (Policy Engine raise)
      'B' — Trust Platform's Sentinel Agent / Coordination Agent raise
    normative_action:
      'HITL'     — session paused for human review
      'REVISION' — AI/agent must self-correct before proceeding
    """
    normative:        Optional[str] = None   # None when verdict is COERCIVE-only
    coercive:         Optional[str] = None   # None when verdict is NORMATIVE-only
    normative_action: Optional[str] = None   # 'HITL' | 'REVISION'
    template_type:    str           = "A"
    rendered_at:      str           = Field(
        default_factory=lambda: datetime.utcnow().isoformat(timespec="seconds") + "Z"
    )


class PolicyEvaluateResponse(BaseModel):
    request_id:         str
    verdict:            Verdict
    rendered_message:   Optional[RenderedMessage]   = None   # primary — rich structured output
    violations:         List[str]                   = Field(default_factory=list)
    response_text:      str                         = ""
    # Human-readable text the SDK should present when a REDACT directive is present.
    # Replaces the first element of the legacy remediations[] list.
    directives:         List[Directive]             = Field(default_factory=list)
    # Actionable SDK instructions (REDACT, REQUIRE_HUMAN_REVIEW).
    # Processed in priority order by the SDK after receiving this response.
    # DEPRECATED ↓ — kept for one release cycle; use response_text + directives instead.
    remediations:       List[str]                   = Field(default_factory=list)
    failed_evaluations: List[FailedEvaluation]      = Field(default_factory=list)
    policies:           List[PolicyResult]          = Field(default_factory=list)
    session_summary:    Optional[SessionSummary]    = None
    pack_trace:         List[dict]                  = Field(default_factory=list)
