"""
Audit writer base types (SRS §4.11 — A1UC-1 AI Interaction Audit Trail).

AuditRecord        — immutable data class; one record per evaluation event.
AuditWriter        — ABC; write() implementations MUST be thread-safe.
CompositeAuditWriter — fan-out to N writers; isolates per-writer failures.

SRS §4.11 mandatory fields (all present in AuditRecord):
  interaction_id    — unique per turn (UUID generated by PE)
  session_id        — groups turns; None for stateless evaluations
  app_id            — calling application
  agent_id          — NHI-verified agent identity (None if NHI not active)
  request_id        — OTel Trace ID (primary cross-platform correlation key)
  timestamp_utc     — UTC timestamp of evaluation
  content_role      — interception point (user_prompt / llm_response / agent_to_agent)
  verdict           — synthesized verdict
  violations        — violation descriptions
  remediations      — remediation instructions
  metadata          — optional SDK-supplied context
"""
from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import List, Optional

logger = logging.getLogger(__name__)


@dataclass
class AuditRecord:
    """
    One evaluation event.  All fields are JSON-serialisable.

    Core fields (SRS §4.11)
    -----------------------
    interaction_id    PE-generated UUID; unique per turn.
    session_id        SDK-supplied session grouping key.  None = stateless.
    request_id        OTel Trace ID — primary correlation key across platform.
    app_id            Application identifier.
    agent_id          NHI-verified agent identity (None if NHI not active).
    timestamp         ISO-8601 UTC string.
    role              Interception point: user_prompt | llm_response | agent_to_agent.
    verdict           Synthesized verdict: PERMISSIVE | NORMATIVE | COERCIVE.
    violations        All non-permissive violation descriptions.
    remediations      Remediation instructions for each violation.
    metadata          Optional SDK-supplied key-value context (model, temp, etc.).

    Phase 4 session fields
    ----------------------
    turn_number       1-based turn index within the session (1 = first turn).
    session_verdict   Verdict produced by cumulative session-level MRA.
                      None when session_id is not supplied.
    session_escalated True when session_verdict > turn_verdict (session caused
                      the final result to be stricter than the per-turn result).

    Observability fields
    --------------------
    latency_ms        Wall-clock time from evaluate() entry to return (ms).
    dimension_results Per-dimension detail: [{dimension, score, status, provider}].
    fail_reason       Reason code on fail-safe path, else None.
                      Values: guardrail_timeout | guardrail_http_error |
                              guardrail_unreachable | no_eval_results
    """
    # SRS §4.11 mandatory
    interaction_id:    str
    request_id:        str
    app_id:            str
    timestamp:         str
    role:              str
    verdict:           str
    violations:        List[str]  = field(default_factory=list)
    remediations:      List[str]  = field(default_factory=list)

    # SRS §4.11 optional
    session_id:        Optional[str] = None
    agent_id:          Optional[str] = None
    metadata:          Optional[dict] = None

    # Phase 4 session fields
    turn_number:       Optional[int]  = None
    session_verdict:   Optional[str]  = None
    session_escalated: bool           = False

    # Observability
    latency_ms:         float          = 0.0
    dimension_results:  List[dict]     = field(default_factory=list)
    fail_reason:        Optional[str]  = None
    # Platform-recommended action derived from verdict:
    #   PERMISSIVE → pass  |  NORMATIVE → warned  |  COERCIVE → blocked
    enforcement_action: Optional[str]  = None

    # Policy chain trace (present when ChainExecutor is active)
    # One entry per pack considered (activated or skipped).
    pack_trace:        List[dict]     = field(default_factory=list)

    # Content capture (optional — populated when STORE_CONTENT_SNIPPETS=true)
    # Full evaluated text is NOT stored in the record; SqliteAuditWriter
    # truncates to CONTENT_SNIPPET_MAX_CHARS and stores the SHA-256 separately.
    content:           Optional[str]  = None


class AuditWriter(ABC):
    """Write a single audit record.  Implementations must be thread-safe."""

    @abstractmethod
    def write(self, record: AuditRecord) -> None: ...


class CompositeAuditWriter(AuditWriter):
    """
    Fan-out writer: delivers each record to every registered writer in order.

    A failure in one writer is caught and logged; the remaining writers still
    receive the record so a broken console writer cannot silence the JSONL file.
    """

    def __init__(self, *writers: AuditWriter):
        self._writers = list(writers)

    def write(self, record: AuditRecord) -> None:
        for w in self._writers:
            try:
                w.write(record)
            except Exception as exc:
                logger.error(
                    f"AuditWriter {w.__class__.__name__} failed for "
                    f"request_id={record.request_id}: {exc}"
                )
